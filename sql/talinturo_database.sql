-- Talinturo database schema
-- PostgreSQL
-- IDs use BIGINT identity columns because the ERD does not specify ID data types.
-- Content/response fields use JSONB where they may store structured activity data.

BEGIN;

CREATE TABLE IF NOT EXISTS users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_salt TEXT,
    password_hash TEXT,
    role VARCHAR(40) NOT NULL DEFAULT 'learner',
    learner_type VARCHAR(60),
    learning_goal TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS learning_paths (
    path_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(120) NOT NULL UNIQUE,
    title VARCHAR(200) NOT NULL,
    description TEXT,
    level VARCHAR(60),
    is_published BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS lessons (
    lesson_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    path_id BIGINT NOT NULL REFERENCES learning_paths(path_id) ON DELETE CASCADE,
    slug VARCHAR(120) NOT NULL UNIQUE,
    title VARCHAR(200) NOT NULL,
    description TEXT,
    duration_minutes INTEGER CHECK (duration_minutes IS NULL OR duration_minutes >= 0),
    content JSONB,
    image_url TEXT,
    video_url TEXT
);

ALTER TABLE lessons
    ADD COLUMN IF NOT EXISTS image_url TEXT,
    ADD COLUMN IF NOT EXISTS video_url TEXT;

CREATE TABLE IF NOT EXISTS signs (
    sign_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id BIGINT NOT NULL REFERENCES lessons(lesson_id) ON DELETE CASCADE,
    slug VARCHAR(120) NOT NULL UNIQUE,
    word VARCHAR(150) NOT NULL,
    meaning TEXT,
    category VARCHAR(100),
    hint TEXT,
    media_url TEXT,
    is_published BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS activities (
    activity_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    path_id BIGINT NOT NULL REFERENCES learning_paths(path_id) ON DELETE CASCADE,
    slug VARCHAR(120) NOT NULL UNIQUE,
    activity_type VARCHAR(80) NOT NULL,
    title VARCHAR(200) NOT NULL,
    content JSONB,
    is_published BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS lesson_progress (
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    lesson_id BIGINT NOT NULL REFERENCES lessons(lesson_id) ON DELETE CASCADE,
    status VARCHAR(40) NOT NULL DEFAULT 'not_started',
    progress_percent NUMERIC(5,2) NOT NULL DEFAULT 0
        CHECK (progress_percent >= 0 AND progress_percent <= 100),
    best_score NUMERIC(7,2) CHECK (best_score IS NULL OR best_score >= 0),
    started_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, lesson_id)
);

CREATE TABLE IF NOT EXISTS activity_attempts (
    attempt_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    activity_id BIGINT NOT NULL REFERENCES activities(activity_id) ON DELETE CASCADE,
    score NUMERIC(7,2) CHECK (score IS NULL OR score >= 0),
    status VARCHAR(40) NOT NULL DEFAULT 'in_progress',
    response JSONB,
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS sign_favorites (
    favorite_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    sign_id BIGINT NOT NULL REFERENCES signs(sign_id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, sign_id)
);

CREATE TABLE IF NOT EXISTS achievements (
    achievement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(120) NOT NULL UNIQUE,
    title VARCHAR(200) NOT NULL,
    description TEXT,
    criteria JSONB
);

CREATE TABLE IF NOT EXISTS user_achievements (
    user_achievement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    achievement_id BIGINT NOT NULL REFERENCES achievements(achievement_id) ON DELETE CASCADE,
    earned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_published BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (user_id, achievement_id)
);

CREATE TABLE IF NOT EXISTS user_preferences (
    preference_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(user_id) ON DELETE CASCADE,
    theme_mode VARCHAR(30) NOT NULL DEFAULT 'light',
    reminders BOOLEAN NOT NULL DEFAULT TRUE,
    sound BOOLEAN NOT NULL DEFAULT TRUE,
    reduced_motion BOOLEAN NOT NULL DEFAULT FALSE,
    weekly_summary BOOLEAN NOT NULL DEFAULT TRUE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE user_preferences
    ADD COLUMN IF NOT EXISTS reminders BOOLEAN NOT NULL DEFAULT TRUE;

CREATE TABLE IF NOT EXISTS classrooms (
    classroom_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instructor_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    name VARCHAR(200) NOT NULL,
    description TEXT,
    invite_code VARCHAR(100) NOT NULL UNIQUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS classroom_memberships (
    membership_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    classroom_id BIGINT NOT NULL REFERENCES classrooms(classroom_id) ON DELETE CASCADE,
    status VARCHAR(40) NOT NULL DEFAULT 'pending',
    joined_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    invited_email VARCHAR(255),
    UNIQUE (user_id, classroom_id)
);

CREATE TABLE IF NOT EXISTS oauth_accounts (
    account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    provider VARCHAR(80) NOT NULL,
    subject VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (provider, subject)
);

-- Helpful indexes for foreign-key lookups and common user-specific queries.
CREATE INDEX IF NOT EXISTS idx_lessons_path_id ON lessons(path_id);
CREATE INDEX IF NOT EXISTS idx_signs_lesson_id ON signs(lesson_id);
CREATE INDEX IF NOT EXISTS idx_activities_path_id ON activities(path_id);
CREATE INDEX IF NOT EXISTS idx_activity_attempts_user_id ON activity_attempts(user_id);
CREATE INDEX IF NOT EXISTS idx_activity_attempts_activity_id ON activity_attempts(activity_id);
CREATE INDEX IF NOT EXISTS idx_classroom_memberships_classroom_id ON classroom_memberships(classroom_id);
CREATE INDEX IF NOT EXISTS idx_classroom_memberships_user_id ON classroom_memberships(user_id);
CREATE INDEX IF NOT EXISTS idx_classrooms_instructor_id ON classrooms(instructor_id);
CREATE INDEX IF NOT EXISTS idx_sign_favorites_sign_id ON sign_favorites(sign_id);
CREATE INDEX IF NOT EXISTS idx_user_achievements_achievement_id ON user_achievements(achievement_id);

COMMIT;
